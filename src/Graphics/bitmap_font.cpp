void BitmapFont::DrawChar(Framebuffer* framebuffer, char c, int x, int y, const Framebuffer::Color& color) {
    // char is always in range 0-255 when cast to unsigned
    
    const uint8_t* charData = fontData[(unsigned char)c];
    
    // Draw 8x8 character
    for (int row = 0; row < 8; row++) {
        uint8_t rowData = charData[row];
        for (int col = 0; col < 8; col++) {
            if (rowData & (0x80 >> col)) {
                framebuffer->writePixel(x + col, y + row, color, 0.0f, false);
            }
        }
    }
}

void BitmapFont::DrawString(Framebuffer* framebuffer, const std::string& text, int x, int y, const Framebuffer::Color& color) {
    int currentX = x;
    for (char c : text) {
        DrawChar(framebuffer, c, currentX, y, color);
        currentX += 8; // Move to next character position
    }
}